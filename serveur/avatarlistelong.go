// FondAvatar renvoie l'illustration du skin classique du personnage.
func FondAvatar(avatar string) string {
	valide := false
	for _, nom := range ListeAvatars() {
		if nom == avatar {
			valide = true
			break
		}
	}
	if !valide {
		return ""
	}
	exceptions := map[string]string{
		"Bel'Veth": "Belveth", "Cho'Gath": "Chogath",
		"K'Santé": "KSante", "Kai'Sa": "Kaisa", "Kha'Zix": "Khazix",
		"LeBlanc": "Leblanc", "Maître Yi": "MasterYi",
		"Nunu et Willump": "Nunu", "Rek'Sai": "RekSai",
		"Séraphine": "Seraphine", "Vel'Koz": "Velkoz",
		"Wukong": "MonkeyKing", "Zoé": "Zoe",
	}
	id, ok := exceptions[avatar]
	if !ok {
		id = strings.NewReplacer(" ", "", "'", "", ".", "").Replace(avatar)
	}
	return "https://ddragon.leagueoflegends.com/cdn/img/champion/splash/" + id + "_0.jpg"
}
